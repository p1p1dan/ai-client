describe('codexRuntime — turns are isolated from one another', () => {
  /** Codex never reuses a turn id; the second replay must not either. */
  const SECOND_TURN = '019fd82d-aeb2-7f32-8eed-000000000002';

  /** Two full turns on one session, the second re-stamped with its own turn id. */
  async function twoTurns(): Promise<{ h: Harness; first: string[]; second: string[] }> {
    // `answerTurnStart: false` so each turn's id is learned from ITS OWN stream
    // rather than from one canned response reused for both — otherwise the
    // second turn would be handed the first turn's id by the harness.
    const h = await turnSession({ answerTurnStart: false });
    void h.runtime.send({ sessionId: 's1', text: PROMPT });
    replayRecordedTurn(h);
    const first = h.events.map((event) => String(payload(event).messageId ?? ''));
    h.events.length = 0;
    void h.runtime.send({ sessionId: 's1', text: 'second turn' });
    replayRecordedTurn(h, { turnId: SECOND_TURN });
    const second = h.events.map((event) => String(payload(event).messageId ?? ''));
    return { h, first, second };
  }

  it('gives the second turn a fresh normalizer, so the first cannot suppress it', async () => {
    // A normalizer kept across turns would still hold turn 1's `settledTools`
    // and `streamedItems` keyed on these very item ids, so turn 2 would render
    // no tool row and no assistant text: a turn that silently draws nothing.
    const { h } = await twoTurns();

    expect(h.eventsOf('tool.started')).toHaveLength(1);
    expect(h.eventsOf('tool.completed')).toHaveLength(1);
    expect(terminalsOf(h.events)).toEqual(['session.completed']);
    expect(h.requestsFor('turn/start')).toHaveLength(2);
  });

  it('addresses the second turn s blocks to a second assistant message', async () => {
    const { first, second } = await twoTurns();

    const assistant = second.filter((id) => id.startsWith('codex-asst-'));
    expect(assistant.length).toBeGreaterThan(0);
    // Nothing in turn 2 addresses turn 1's envelope: a block appended to a
    // message the renderer already completed is a block dropped on the floor.
    for (const id of assistant) expect(first).not.toContain(id);
  });

  it('drops a frame that lands after the terminal instead of folding it into the next turn', async () => {
    // The registered cost of retiring the turn on `turn/completed`: a trailing
    // `thread/tokenUsage/updated` is lost. Losing a usage refresh is cheaper
    // than resurrecting a finished turn — but it has to be a DROP, not an event
    // attributed to whatever turn comes next.
    const h = await turnSession();
    await h.runtime.send({ sessionId: 's1', text: PROMPT });
    replayRecordedTurn(h);
    h.events.length = 0;
    h.push({
      method: 'thread/tokenUsage/updated',
      params: { threadId: FIXTURE_THREAD, totalTokenUsage: { totalTokens: 1 } },
    });

    expect(h.eventsOf('usage.updated')).toHaveLength(0);
    expect(h.logs.some((line) => line.includes('outside a turn'))).toBe(true);
  });

  it('does not let another thread s turn/completed retire this session s turn', async () => {
    // C12 — one session ≡ one thread — is already enforced for status frames
    // (`WARN codex status for a foreign thread, ignored`). The turn loop must
    // not be the hole in it: the normalizer DROPS a foreign frame, so retiring
    // the turn on it and claiming `terminalAlreadyEmitted` asserts an event that
    // was never sent. The result is the worst combination available — no
    // terminal AND no turn record: the assistant bubble streams forever, the
    // renderer keeps the session busy, and the real `turn/completed` that
    // follows is dropped as "outside a turn".
    const h = await turnSession();
    await h.runtime.send({ sessionId: 's1', text: PROMPT });
    replayRecordedTurn(h, { upTo: 8 });
    h.events.length = 0;
    h.push({
      method: 'turn/completed',
      params: {
        threadId: 'someone-elses-thread',
        turn: { id: 'other-turn', items: [], status: 'completed' },
      },
    });

    // Ignored outright: no terminal, because none belongs to us...
    expect(terminalsOf(h.events)).toEqual([]);
    // ...and the turn is still ours to finish, so our own frames still land.
    replayRecordedTurn(h, { from: 8 });
    expect(h.eventsOf('session.completed')).toHaveLength(1);
  });
});

