function makeHarness(options: HarnessOptions = {}): Harness {
  const events: Array<Record<string, unknown>> = [];
  const logs: string[] = [];
  const ops: string[] = [];
  const written: OutboundFrame[] = [];
  const connectInputs: Array<Parameters<CodexConnectFactory>[0]> = [];
  const ensureHomeInputs: Array<Parameters<NonNullable<CodexRuntimeOptions['ensureHome']>>[0]> = [];
  const connections: ConnectionSlice[] = [];
  const intervals: FakeTimer[] = [];
  const deadlines: FakeTimer[] = [];
  // A non-zero epoch, so "seeded at construction" and "never set" are different
  // readings rather than both being 0.
  let clock = 1_700_000_000_000;

  function answer(frame: OutboundFrame, core: CodexConnectionCore): void {
    if (frame.id === undefined) return;
    if (frame.method === 'initialize') {
      if (options.answerInitialize === false) return;
      const body = options.initializeError
        ? { id: frame.id, error: options.initializeError }
        : { id: frame.id, result: { codexHome: HOME_DIR } };
      core.pushStdout(`${JSON.stringify(body)}\n`);
      return;
    }
    if (frame.method === 'thread/resume') {
      // The window first, the answer second — in that order, because the whole
      // point of H11 is what happens to a frame that arrives BEFORE the response.
      for (const pushed of options.resumeWindowFrames ?? []) {
        core.pushStdout(`${JSON.stringify(pushed)}\n`);
      }
      const body = options.threadResumeError
        ? { id: frame.id, error: options.threadResumeError }
        : { id: frame.id, result: options.threadResumeResult ?? RESUME_RESULT };
      core.pushStdout(`${JSON.stringify(body)}\n`);
      return;
    }
    if (frame.method === 'thread/turns/list') {
      const body = options.turnsListError
        ? { id: frame.id, error: options.turnsListError }
        : { id: frame.id, result: options.turnsListResult ?? RECORDED_TURNS_LIST };
      core.pushStdout(`${JSON.stringify(body)}\n`);
      return;
    }
    if (frame.method === 'thread/start') {
      const body = options.threadStartError
        ? { id: frame.id, error: options.threadStartError }
        : { id: frame.id, result: options.threadStartResult ?? THREAD_START_RESULT };
      core.pushStdout(`${JSON.stringify(body)}\n`);
      return;
    }
    if (frame.method === 'turn/start') {
      // Silence is a real posture, not a broken fake: whether codex answers
      // `turn/start` at turn START or at turn END is [未测], so the turn loop has
      // to work with the id it has not been told yet.
      if (options.answerTurnStart === false) return;
      const body = options.turnStartError
        ? { id: frame.id, error: options.turnStartError }
        : {
            id: frame.id,
            // `TurnStartResponse` = `{turn: Turn}`, `Turn` requires id/items/status
            // [实测 codex-turn-schema.json].
            result: options.turnStartResult ?? {
              turn: { id: FIXTURE_TURN, items: [], status: 'inProgress' },
            },
          };
      core.pushStdout(`${JSON.stringify(body)}\n`);
      return;
    }
    if (frame.method === 'turn/interrupt') {
      // `TurnInterruptResponse` is an empty object [实测 schema].
      core.pushStdout(`${JSON.stringify({ id: frame.id, result: {} })}\n`);
    }
  }

  const connect: CodexConnectFactory = (input) => {
    connectInputs.push(input);
    const mine: OutboundFrame[] = [];
    const myOps: string[] = [];
    // Assigned one statement below, and only ever read from callbacks that run
    // later — the core has to exist before anything can be written to it.
    let self: CodexConnectionCore | null = null;
    const created = createCodexConnection({
      transport: {
        pid: 4242,
        write: (line) => {
          const frame = JSON.parse(line) as OutboundFrame;
          written.push(frame);
          mine.push(frame);
          const op = frame.method ? `write:${frame.method}` : `reply:${String(frame.id)}`;
          ops.push(op);
          myOps.push(op);
          // A real process never answers inside the write call; a microtask
          // keeps the ordering realistic without a timer. Answered into the link
          // that WROTE it — a latest-wins core would post the answer to a
          // connection the caller is not listening on the moment a revive opens
          // a second one.
          if (frame.method !== undefined && frame.id !== undefined) {
            queueMicrotask(() => {
              if (self) answer(frame, self);
            });
          }
        },
        kill: (reason) => {
          ops.push(`kill:${reason}`);
          myOps.push(`kill:${reason}`);
        },
      },
      handlers: input.handlers,
      log: (...args) =>
        logs.push(args.map((a) => (typeof a === 'string' ? a : JSON.stringify(a))).join(' ')),
    });
    self = created;
    connections.push({
      written: mine,
      ops: myOps,
      requestsFor: (method) => mine.filter((f) => f.method === method),
      push: (frame) => created.pushStdout(`${JSON.stringify(frame)}\n`),
      exit: (info) => created.handleExit(info),
    });
    return created.connection;
  };

  function newest(): ConnectionSlice | undefined {
    return connections[connections.length - 1];
  }

  const registry = new SessionRegistry();
  const runtime = new CodexRuntime({
    emit: (event) => events.push(event),
    log: (...args) =>
      logs.push(args.map((a) => (typeof a === 'string' ? a : JSON.stringify(a))).join(' ')),
    registry,
    codexHomeDir: options.codexHomeDir ?? HOME_DIR,
    appVersion: options.appVersion ?? '9.9.9-test',
    now: () => clock,
    env: options.env ?? {},
    startInterval: collectTimers(intervals),
    startTimeout: collectTimers(deadlines),
    connect,
    resolveLaunch: options.resolveLaunch ?? (() => ({ ok: true, plan: PLAN })),
    ensureHome: (input) => {
      // Recorded before delegating, so the H9 layer-1 WIRING (which posture the
      // runtime hands the home builder) is observable — `codexHome.test.ts` can
      // only pin what the projection does with a posture it is given.
      ensureHomeInputs.push(input);
      return (
        options.ensureHome ??
        ((seen: Parameters<NonNullable<CodexRuntimeOptions['ensureHome']>>[0]) => ({
          mode: 'projected' as const,
          homeDir: seen.homeDir,
          projection: { toml: '', kept: [], dropped: [] },
          authCopied: false,
        }))
      )(input);
    },
  });

  const harness: Harness = {
    runtime,
    registry,
    events,
    logs,
    ops,
    connectInputs,
    ensureHomeInputs,
    requestFor: (method) => {
      const frame = written.find((f) => f.method === method);
      if (!frame) throw new Error(`no outbound request for ${method}; saw ${ops.join(', ')}`);
      return frame;
    },
    requestsFor: (method) => written.filter((f) => f.method === method),
    replies: () => written.filter((f) => f.method === undefined),
    event: (type) => events.find((e) => e.type === type),
    eventsOf: (type) => events.filter((e) => e.type === type),
    push: (frame) => newest()?.push(frame),
    exit: (info) => newest()?.exit(info),
    connections,
    options,
    deadlines,
    advance: (ms) => {
      clock += ms;
    },
    now: () => clock,
    intervals,
    sweeper: () => intervals[intervals.length - 1],
    sweepTick: () => {
      const sweeper = intervals[intervals.length - 1];
      if (!sweeper) throw new Error('no idle sweeper was ever started');
      sweeper.fire();
    },
    waitFor: async (check, what) => {
      for (let i = 0; i < 200; i += 1) {
        if (check()) return;
        await new Promise((resolve) => setTimeout(resolve, 2));
      }
      throw new Error(`timed out waiting for ${what}`);
    },
    waitForEvent: async (type) => {
      await harness.waitFor(() => events.some((e) => e.type === type), `event ${type}`);
      return events.find((e) => e.type === type) as Record<string, unknown>;
    },
  };
  return harness;
}

type Payload = Record<string, unknown>;

function payload(event: Record<string, unknown> | undefined): Payload {
  return (event?.payload ?? {}) as Payload;
}

