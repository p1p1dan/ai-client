interface FixtureEnvelope {
  dir: string;
  tMs: number | null;
  raw: { method?: string; params?: Record<string, unknown>; id?: number };
}

/** The recorded turn, `<-` frames only, in capture order. */
function loadTurnFixture(file: string): FixtureEnvelope[] {
  return readFileSync(path.join(FIXTURES, file), 'utf8')
    .split('\n')
    .filter((line) => line.trim().length > 0)
    .map((line) => JSON.parse(line) as FixtureEnvelope)
    .filter((frame) => frame.dir === '<-' && frame.raw.method !== undefined);
}

