/**
 * S3 slices 2a + 2c — the Codex runtime shell and its turn loop.
 *
 * The gate item lives in the first describe: the posture that reaches
 * `thread/start` and the posture `session.created` advertises are compared TO
 * EACH OTHER, never to a literal (paradigm from
 * `claudeRuntimeOptions.test.ts:151-219`). A literal on both sides passes while
 * the two drift apart; comparing the captures cannot.
 *
 * The 2c half is verified by replaying the one complete recorded turn we own
 * (`fixtures/codex/codex-filechange-approval-turn.jsonl`, 19 frames) through the
 * REAL connection core, so what is asserted is the wiring that ships: which
 * frames we write, in what order, and which events come out. The failures that
 * matter in a turn loop are ordering and ownership failures, and no amount of
 * isolated unit tests catches those.
 *
 * Everything runs against an in-memory transport driving the real
 * `createCodexConnection` core, so no process is spawned and no quota is spent.
 */

