/**
 * S3 slice 3 — the question bridge, at the runtime level.
 *
 * `codexQuestionBridge.test.ts` covers the translation in isolation; what can
 * only be tested here is ownership and ordering: which events leave the
 * runtime, which frames reach the wire, and what happens when the server
 * settles a request out from under a card that is still on screen.
 */
describe('codexRuntime — the question bridge (slice 3)', () => {
  const QUESTION_FIXTURE = readFileSync(
    path.join(FIXTURES, 'codex-question-requests.jsonl'),
    'utf8'
  )
    .split('\n')
    .filter((line) => line.trim().length > 0)
    .map((line) => JSON.parse(line) as FixtureEnvelope);

  /** The first real captured request: 3 questions, ids prod_host / db_url / telemetry. */
  const REAL_REQUEST = QUESTION_FIXTURE.find(
    (frame) => frame.dir === '<-' && frame.raw.method === 'item/tool/requestUserInput'
  );
  if (!REAL_REQUEST?.raw.params) throw new Error('question fixture lost its request frame');
  const QUESTION_THREAD = REAL_REQUEST.raw.params.threadId as string;
  const QUESTION_ID = 'codex:s1:n:0';

  /** A session bound to the QUESTION fixture's thread, mid-turn. */
  async function askingSession(): Promise<Harness> {
    const h = makeHarness({
      threadStartResult: {
        threadId: QUESTION_THREAD,
        approvalPolicy: 'on-request',
        sandbox: { type: 'workspaceWrite', networkAccess: false },
      },
    });
    h.runtime.createSession({ sessionId: 's1', workspacePath: '/work/repo' });
    await h.waitForEvent('session.created');
    await h.runtime.send({ sessionId: 's1', text: 'go', requestId: 'req-send' });
    h.events.length = 0;
    return h;
  }

  function askReal(h: Harness, id = 0): void {
    h.push({ id, method: 'item/tool/requestUserInput', params: REAL_REQUEST?.raw.params });
  }

  function resolvedNotification(requestId: number, threadId = QUESTION_THREAD) {
    return { method: 'serverRequest/resolved', params: { threadId, requestId } };
  }

  it('raises a card from a real captured request, carrying the ids the answers need', async () => {
    const h = await askingSession();
    askReal(h);

    const requested = h.eventsOf('question.requested');
    expect(requested).toHaveLength(1);
    const body = payload(requested[0]);
    expect(body.questionId).toBe(QUESTION_ID);
    expect((body.questions as Array<{ id: string }>).map((q) => q.id)).toEqual([
      'prod_host',
      'db_url',
      'telemetry',
    ]);
    // `null` means "never auto-resolves" and is passed through as captured.
    expect(body.autoResolutionMs).toBeNull();
    // Nothing is answered yet: the card is the whole point of parking.
    expect(h.replies()).toHaveLength(0);
  });

  it('writes the answer body to the wire and resolves the card exactly once', async () => {
    const h = await askingSession();
    askReal(h);
    h.runtime.respondQuestion({
      sessionId: 's1',
      questionId: QUESTION_ID,
      answers: {
        prod_host: 'Keep current host',
        db_url: 'Use environment variable',
        telemetry: 'Disable',
      },
      requestId: 'req-answer',
    });

    expect(h.replies()).toHaveLength(1);
    expect(h.replies()[0]).toMatchObject({
      id: 0,
      result: {
        answers: {
          prod_host: { answers: ['Keep current host'] },
          db_url: { answers: ['Use environment variable'] },
          telemetry: { answers: ['Disable'] },
        },
      },
    });
    const resolved = h.eventsOf('question.resolved');
    expect(resolved).toHaveLength(1);
    expect(payload(resolved[0]).outcome).toBe('answered');
  });

  it('sends the clean-cancel body on skip and reports it as cancelled, not answered', async () => {
    const h = await askingSession();
    askReal(h);
    h.runtime.respondQuestion({ sessionId: 's1', questionId: QUESTION_ID, cancel: true });

    expect(h.replies()[0]).toMatchObject({ id: 0, result: { answers: {} } });
    // An empty answers map IS the cancel on this wire — the opposite of the
    // Claude bridge, which refuses empty payloads as a footgun guard.
    const resolved = h.eventsOf('question.resolved');
    expect(resolved).toHaveLength(1);
    expect(payload(resolved[0])).toEqual({ questionId: QUESTION_ID, outcome: 'cancelled' });
  });

  it('treats the resolved notification that follows our own answer as a no-op', async () => {
    const h = await askingSession();
    askReal(h);
    h.runtime.respondQuestion({ sessionId: 's1', questionId: QUESTION_ID, cancel: true });
    const repliesBefore = h.replies().length;
    const eventsBefore = h.events.length;

    h.push(resolvedNotification(0));

    // Every request we answer is followed by one of these. It must cost
    // nothing: no second frame, no second event, and a debug line rather than
    // a WARN, or every ordinary question would look like a fault.
    expect(h.replies()).toHaveLength(repliesBefore);
    expect(h.events).toHaveLength(eventsBefore);
    expect(h.logs.some((line) => line.includes('resolved echo for settled id'))).toBe(true);
    expect(h.logs.some((line) => line.includes('WARN codex pending: serverRequest/resolved'))).toBe(
      false
    );
  });

  it('drops the card WITHOUT replying when the server resolves its own request', async () => {
    const h = await askingSession();
    askReal(h);
    h.events.length = 0;

    h.push(resolvedNotification(0));

    // Zero frames is the whole point: the server has stopped waiting, so a
    // reply now would be a response to nothing.
    expect(h.replies()).toHaveLength(0);
    const resolved = h.eventsOf('question.resolved');
    expect(resolved).toHaveLength(1);
    expect(payload(resolved[0])).toEqual({ questionId: QUESTION_ID, outcome: 'rejected' });

    // And the entry really left the table — a later close finds nothing.
    h.runtime.close({ sessionId: 's1' });
    expect(h.replies()).toHaveLength(0);
  });

  it('still consumes the resolved notification after the turn has ended', async () => {
    // The placement guard. This notification is handled ABOVE the "no turn, drop
    // it" branch, because the server settling its own request clusters exactly
    // where a turn is ending. Handled below it, the card would be stranded in
    // precisely the case the consumer exists for.
    const h = await askingSession();
    askReal(h);
    h.runtime.stop({ sessionId: 's1' });
    // Stop drained the table, so re-ask outside a turn is impossible; instead
    // park a fresh request while a turn runs, then end the turn.
    const h2 = await askingSession();
    askReal(h2, 3);
    h2.push({
      method: 'turn/completed',
      params: { threadId: QUESTION_THREAD, turn: { id: FIXTURE_TURN, status: 'completed' } },
    });
    await h2.waitFor(() => h2.eventsOf('session.completed').length > 0, 'turn to finish');
    h2.events.length = 0;

    h2.push(resolvedNotification(3));

    expect(h2.eventsOf('question.resolved')).toHaveLength(1);
    expect(h2.replies()).toHaveLength(0);
  });

  it('ignores a resolved notification for another thread or without a request id', async () => {
    const h = await askingSession();
    askReal(h);
    h.events.length = 0;

    h.push(resolvedNotification(0, 'some-other-thread'));
    h.push({ method: 'serverRequest/resolved', params: { threadId: QUESTION_THREAD } });

    // The card is untouched: neither frame identifies a request of ours.
    expect(h.eventsOf('question.resolved')).toHaveLength(0);
    expect(h.replies()).toHaveLength(0);
  });

  it('refuses a question that arrives after Stop instead of raising a card', async () => {
    const h = await askingSession();
    h.runtime.stop({ sessionId: 's1' });
    h.events.length = 0;
    h.replies().length = 0;
    askReal(h, 5);

    // `stop()` neither disposes nor deletes the session and the interrupt is
    // best effort, so codex can keep asking. A card here would drag the session
    // back into a busy state the user just left.
    expect(h.eventsOf('question.requested')).toHaveLength(0);
    expect(h.eventsOf('question.resolved')).toHaveLength(0);
    expect(h.replies().filter((frame) => frame.id === 5)).toHaveLength(1);
    expect(h.replies().find((frame) => frame.id === 5)?.result).toEqual({ answers: {} });
  });

  it('resolves the card on stop and on close, with the frame written before the kill', async () => {
    const h = await askingSession();
    askReal(h);
    h.events.length = 0;
    h.runtime.stop({ sessionId: 's1' });

    expect(h.replies()).toHaveLength(1);
    expect(h.replies()[0]).toMatchObject({ id: 0, result: { answers: {} } });
    expect(payload(h.event('question.resolved'))).toEqual({
      questionId: QUESTION_ID,
      outcome: 'rejected',
    });

    const c = await askingSession();
    askReal(c);
    c.events.length = 0;
    c.runtime.close({ sessionId: 's1' });
    expect(c.replies()).toHaveLength(1);
    expect(c.ops.indexOf('reply:0')).toBeLessThan(c.ops.findIndex((op) => op.startsWith('kill:')));
    expect(c.eventsOf('question.resolved')).toHaveLength(1);
  });

  it('resolves the card when the process dies, and does NOT pretend a frame was sent', async () => {
    const h = await askingSession();
    askReal(h);
    h.events.length = 0;
    h.exit({ code: 1, signal: null });

    // The asymmetry is real and must not be papered over with a mock: the
    // process is already gone, so the write is dropped by the connection. What
    // still has to happen is the card resolving — otherwise it sits pending
    // forever on a session that has failed.
    expect(h.replies()).toHaveLength(0);
    expect(h.eventsOf('question.resolved')).toHaveLength(1);
    expect(payload(h.event('question.resolved')).outcome).toBe('rejected');
  });

  it('emits no session.status anywhere on the question path (C10 rule 3)', async () => {
    // Asserted on the RUNTIME's emit array, not on the bridge: the bridge is a
    // pure function with no emit channel, so asserting it there would pass no
    // matter where the status was actually written.
    const h = await askingSession();
    askReal(h);
    h.runtime.respondQuestion({
      sessionId: 's1',
      questionId: QUESTION_ID,
      answers: { prod_host: 'Keep current host' },
    });

    expect(h.events.map((event) => event.type)).toEqual([
      'question.requested',
      'question.resolved',
    ]);

    // The waiting state comes from the server's own snapshot instead, which it
    // does send around every question [实测 codex-question-turn-status.jsonl].
    h.push({
      method: 'thread/status/changed',
      params: {
        threadId: QUESTION_THREAD,
        status: { type: 'active', activeFlags: ['waitingOnUserInput'] },
      },
    });
    expect(payload(h.eventsOf('session.status').at(-1)).status).toBe('waiting_question');
  });

  it('rejects an id that belongs to a different kind of request', async () => {
    const h = await askingSession();
    h.push({ id: 0, method: 'item/commandExecution/requestApproval', params: {} });
    h.events.length = 0;
    h.runtime.respondQuestion({
      sessionId: 's1',
      questionId: QUESTION_ID,
      answers: { a: 'yes' },
      requestId: 'req-q',
    });

    // A shape error, not a race: nothing to converge, so this one IS an error.
    expect(payload(h.event('host.error')).code).toBe('invalid_payload');
    expect(h.eventsOf('question.resolved')).toHaveLength(0);
    expect(h.replies()).toHaveLength(0);
  });
});

/**
 * S3 slice 4 — the approval bridge, at the runtime level.
 *
 * `codexDecisions.test.ts` covers the dialect translation in isolation. What
 * can only be proved here is the wiring: which card leaves the runtime, WHEN a
 * JSON-RPC frame is written (never before a human decided), and what happens to
 * a card whose request stops existing under it — the four ways an approval can
 * leave the pending table without an answer.
 *
 * Two evidence grades are mixed on purpose and are labelled per use:
 *   [实测]  — params lifted verbatim from a captured frame.
 *   [构造]  — a shape the test builds, because no capture holds one.
 */
describe('codexRuntime — the approval bridge (slice 4)', () => {
  /**
   * The one real `item/commandExecution/requestApproval` we own, params
   * verbatim: command, cwd, and an `availableDecisions` of
   * `["accept", {acceptWithExecpolicyAmendment}, "cancel"]` — the frame that
   * makes "offer exactly what the server listed" produce a card whose only
   * refusal kills the turn.
   */
  const EXEC_FRAME = loadTurnFixture('codex-command-approval.jsonl').find(
    (frame) => frame.raw.method === 'item/commandExecution/requestApproval'
  );
  if (!EXEC_FRAME?.raw.params) throw new Error('command approval fixture lost its request frame');
  const EXEC_PARAMS = EXEC_FRAME.raw.params;
  const EXEC_METHOD = 'item/commandExecution/requestApproval';
  const EXEC_THREAD = EXEC_PARAMS.threadId as string;

  /**
   * [构造] — the JSON-RPC id is supplied BY THE TEST.
   *
   * The fixture file does carry `"id": 0` on this frame, but its README records
   * that field as INFERRED from the same turn's `serverRequest/resolved
   * {requestId: 0}`, not captured: the source report stored `method` + `params`
   * only. The id is therefore stated here, where its provenance can be read,
   * rather than borrowed from a file the manifest forbids "completing".
   */
  const EXEC_APPROVAL_ID = 0;

  /** The recorded fileChange approval params [实测]: reason null, grantRoot null. */
  const FILE_CHANGE_PARAMS = loadTurnFixture('codex-filechange-approval-turn.jsonl').find(
    (frame) => frame.raw.method === APPROVAL_METHOD
  )?.raw.params;
  if (!FILE_CHANGE_PARAMS) throw new Error('fileChange fixture lost its approval frame');

  /** A session bound to the EXEC fixture's thread, mid-turn. */
  async function execSession(): Promise<Harness> {
    const h = makeHarness({
      threadStartResult: {
        threadId: EXEC_THREAD,
        approvalPolicy: 'on-request',
        sandbox: { type: 'workspaceWrite', networkAccess: false },
      },
    });
    h.runtime.createSession({ sessionId: 's1', workspacePath: '/work/repo' });
    await h.waitForEvent('session.created');
    await h.runtime.send({ sessionId: 's1', text: PROMPT });
    h.events.length = 0;
    return h;
  }

  function pushExec(h: Harness, params: unknown = EXEC_PARAMS, id = EXEC_APPROVAL_ID): void {
    h.push({ id, method: EXEC_METHOD, params });
  }

  /**
   * The recorded turn replayed up to — but NOT including — its approval request,
   * so the approval params can be doctored while the `item/started` that carries
   * the patch has already landed under the same itemId.
   */
  async function approvalReadyTurn(): Promise<Harness> {
    const h = await turnSession();
    await h.runtime.send({ sessionId: 's1', text: PROMPT });
    replayRecordedTurn(h, { upTo: 9 });
    return h;
  }

  function pushFileChange(h: Harness, params: unknown = FILE_CHANGE_PARAMS): void {
    h.push({ id: APPROVAL_ID, method: APPROVAL_METHOD, params });
  }

  function detailOf(event: Record<string, unknown> | undefined): Record<string, unknown> {
    return (payload(event).detail ?? {}) as Record<string, unknown>;
  }

  describe('A5 — the real exec frame becomes a card, verbatim', () => {
    it('carries kind, command, cwd, the offered decisions and the omitted count', async () => {
      const h = await execSession();
      pushExec(h);

      const requested = h.eventsOf('permission.requested');
      expect(requested).toHaveLength(1);
      const body = payload(requested[0]);
      expect(body.permissionId).toBe(permissionIdOf(EXEC_APPROVAL_ID));
      expect(body.kind).toBe('exec');
      expect(body.toolName).toBe('Run command');
      const detail = detailOf(requested[0]);
      expect(detail.kind).toBe('exec');
      expect(detail.command).toBe(EXEC_PARAMS.command);
      expect(detail.cwd).toBe(EXEC_PARAMS.cwd);
      // The object variant ("approve and persist an execpolicy rule") is not
      // modelled, so it is COUNTED rather than dropped in silence...
      expect(body.omittedDecisionCount).toBe(1);
      // ...and the card still offers a plain Deny, which this frame never
      // listed: without it the only refusal on screen aborts the whole turn.
      expect(body.decisions).toEqual(['allow', 'deny', 'cancel']);
    });

    it('does not answer the request while the card is on screen', async () => {
      const h = await execSession();
      pushExec(h);

      // The one failure this whole bridge exists to prevent: replying before a
      // human decided is deciding FOR them.
      expect(h.replies()).toHaveLength(0);
      expect(h.eventsOf('permission.resolved')).toHaveLength(0);
    });

    it('does not carry `input`, which has no Codex counterpart', async () => {
      const h = await execSession();
      pushExec(h);

      // `input` is the Claude tool's arguments. Filling it with the approval
      // params would put a second, differently-shaped body on the card.
      expect(payload(h.event('permission.requested'))).not.toHaveProperty('input');
    });
  });

  describe('A15 — the justification is written under the protocol key `reason`', () => {
    it('writes `reason`, never `description`', async () => {
      const h = await execSession();
      // [构造] — the captured exec frame has no `reason`; the field is real and
      // optional per the generated contract.
      pushExec(h, { ...EXEC_PARAMS, reason: 'needs network access to fetch deps' });

      const body = payload(h.event('permission.requested'));
      expect(body.reason).toBe('needs network access to fetch deps');
      // The two are separate protocol fields. Writing `description` here and
      // reading `reason` in the store loses every Codex justification, silently.
      expect(body).not.toHaveProperty('description');
    });

    it('omits the key entirely when codex sent none, rather than writing an empty string', async () => {
      const h = await execSession();
      pushExec(h);
      expect(payload(h.event('permission.requested'))).not.toHaveProperty('reason');

      const nulled = await approvalReadyTurn();
      pushFileChange(nulled); // the recorded frame carries `reason: null` [实测]
      expect(FILE_CHANGE_PARAMS.reason).toBeNull();
      expect(payload(nulled.event('permission.requested'))).not.toHaveProperty('reason');
    });
  });

  describe('A8 — an exec approval that is not about a command still has a body', () => {
    it('projects networkApprovalContext and additionalPermissions, with a null command', async () => {
      const h = await execSession();
      // [构造] — a managed-network approval. No capture exists; the shape is the
      // generated contract's (`NetworkApprovalContext` requires host+protocol,
      // `AdditionalPermissionProfile` is fileSystem + network).
      pushExec(h, {
        ...EXEC_PARAMS,
        command: null,
        networkApprovalContext: { host: 'registry.npmjs.org', protocol: 'https' },
        additionalPermissions: {
          fileSystem: { entries: [{ path: '/etc' }, { path: '/var' }] },
          network: { enabled: true },
        },
      });

      const detail = detailOf(h.event('permission.requested'));
      // `command: null` is a DECLARED shape (zsh-exec-bridge subcommands), so
      // the card must not degrade to an empty box — and must not auto-decline,
      // which would make a whole class of approvals unusable.
      expect(detail).not.toHaveProperty('command');
      expect(detail.network).toEqual({ host: 'registry.npmjs.org', protocol: 'https' });
      expect(detail.extraPermissions).toEqual({ fileSystemEntries: 2, networkRequested: true });
      expect(detail.cwd).toBe(EXEC_PARAMS.cwd);
      expect(h.replies()).toHaveLength(0);
      expect(h.eventsOf('permission.requested')).toHaveLength(1);
    });

    it('reports extras that ask for no network as exactly that', async () => {
      const h = await execSession();
      pushExec(h, { ...EXEC_PARAMS, additionalPermissions: { fileSystem: {} } });

      // Counted, never expanded (the profile is recursive and unsampled), but
      // the fact that extras exist at all has to reach the card.
      expect(detailOf(h.event('permission.requested')).extraPermissions).toEqual({
        fileSystemEntries: 0,
        networkRequested: false,
      });
    });

    it('writes neither key when the request carries nothing to say', async () => {
      const h = await execSession();
      pushExec(h, {
        ...EXEC_PARAMS,
        additionalPermissions: null,
        // Half a context is not a context: a host with no protocol would render
        // `undefined://host`.
        networkApprovalContext: { host: 'example.com' },
      });

      const detail = detailOf(h.event('permission.requested'));
      expect(detail).not.toHaveProperty('extraPermissions');
      expect(detail).not.toHaveProperty('network');
      expect(detail.kind).toBe('exec');
    });
  });

  describe('A6 — the diff correlation, and the reply that waits for a human', () => {
    it('(a) real order: the patch from item/started reaches the card', async () => {
      // [实测] — frame 8 (`item/started`, fileChange, with the diff) then frame
      // 10 (the approval), same itemId, 1ms apart. This IS the correlation.
      const h = await stoppableTurn();

      const body = payload(h.event('permission.requested'));
      expect(body.kind).toBe('file_change');
      expect(body.toolName).toBe('Apply patch');
      const changes = detailOf(h.event('permission.requested')).changes as Array<
        Record<string, unknown>
      >;
      expect(changes).toHaveLength(1);
      expect(String(changes[0].path).endsWith('probe_b.txt')).toBe(true);
      expect(changes[0].change).toBe('add');
      expect(changes[0].diff).toBe('hi\n');
      // file_change requests carry NO availableDecisions [实测], which is their
      // normal path, not an error path.
      expect(body.decisions).toEqual(['allow', 'deny']);
      expect(body).not.toHaveProperty('omittedDecisionCount');
    });

    it('(b) [构造] reversed order: the card is still raised, only the patch is missing', async () => {
      // The frames are swapped BY THE TEST — no capture shows this order. Hard
      // constraint 7: a missing diff degrades the card, it never delays it and
      // it never answers early.
      const h = await turnSession();
      await h.runtime.send({ sessionId: 's1', text: PROMPT });
      replayRecordedTurn(h, { upTo: 7 }); // everything BEFORE the fileChange item/started
      pushFileChange(h);

      expect(h.eventsOf('permission.requested')).toHaveLength(1);
      expect(detailOf(h.event('permission.requested'))).toEqual({
        kind: 'file_change',
        changes: [],
      });
      expect(h.replies()).toHaveLength(0);
    });

    it('(c) zero wire frames until the click, then exactly one', async () => {
      const h = await stoppableTurn();
      expect(h.replies()).toHaveLength(0);

      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: true,
        decision: 'allow',
      });

      expect(h.replies()).toHaveLength(1);
      expect(h.replies()[0]).toMatchObject({ id: APPROVAL_ID, result: { decision: 'accept' } });
    });
  });

  describe('A7 — grantRoot is what an Allow really grants', () => {
    it('is absent when codex did not ask for one', async () => {
      expect(FILE_CHANGE_PARAMS.grantRoot).toBeNull();
      const h = await stoppableTurn();

      expect(detailOf(h.event('permission.requested'))).not.toHaveProperty('grantRoot');
    });

    it('[构造] reaches the detail when it is set, alongside the patch', async () => {
      const h = await approvalReadyTurn();
      pushFileChange(h, { ...FILE_CHANGE_PARAMS, grantRoot: '/work/repo' });

      const detail = detailOf(h.event('permission.requested'));
      // Not a substitute for the patch — BOTH, or the card shows a one-file
      // patch while the Allow hands over a directory for the whole session.
      expect(detail.grantRoot).toBe('/work/repo');
      expect((detail.changes as unknown[]).length).toBe(1);
    });
  });

  describe('A9 / A2 — respondPermission on a parked request', () => {
    it('A9 — one wire frame, one resolved carrying the decision and no autoReason', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: true,
        decision: 'allow_session',
        requestId: 'req-perm',
      });

      expect(h.replies()).toHaveLength(1);
      expect(h.replies()[0]).toMatchObject({
        id: APPROVAL_ID,
        result: { decision: 'acceptForSession' },
      });
      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      // No autoReason: a human decided, and claiming otherwise is the exact
      // dishonesty the field was added to remove.
      expect(payload(resolved[0])).toEqual({
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: true,
        decision: 'allow_session',
      });

      // The entry left the table: a later close cannot answer id 0 again.
      h.runtime.close({ sessionId: 's1' });
      expect(h.replies().filter((frame) => frame.id === APPROVAL_ID)).toHaveLength(1);
      expect(h.eventsOf('permission.resolved')).toHaveLength(1);
    });

    it('A9 — a plain deny sends the decline word and reports allow:false', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        decision: 'deny',
      });

      expect(h.replies()[0]).toMatchObject({ id: APPROVAL_ID, result: { decision: 'decline' } });
      expect(payload(h.event('permission.resolved')).allow).toBe(false);
    });

    it('A2 — an unmappable decision is downgraded to deny on the wire AND on the card', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        // A word from a future build (or a payload that got past the dispatch
        // guard). It must never be forwarded and never guessed at.
        decision: 'allow_forever' as PermissionDecisionId,
        allow: true,
      });

      expect(h.replies()[0]).toMatchObject({ id: APPROVAL_ID, result: { decision: 'decline' } });
      // The card must agree with the wire: painting "Allowed for session" over a
      // frame that said `decline` is the defect this assertion pins.
      expect(payload(h.event('permission.resolved'))).toEqual({
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        decision: 'deny',
      });
      expect(h.logs.some((line) => line.includes('unmappable decision'))).toBe(true);
    });

    it('derives allow from the decision when the caller sent no boolean', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        decision: 'allow',
      });

      expect(h.replies()[0]).toMatchObject({ id: APPROVAL_ID, result: { decision: 'accept' } });
      expect(payload(h.event('permission.resolved')).allow).toBe(true);
    });
  });

  describe('A10 — a click that lands on an id we no longer hold', () => {
    it('converges the card instead of emitting an invisible host.error', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: 'codex:s1:n:99',
        allow: true,
        decision: 'allow',
        requestId: 'req-late',
      });

      // A non-fatal host.error is invisible in the renderer, so it would leave
      // the card unanswerable forever.
      expect(h.eventsOf('host.error')).toHaveLength(0);
      expect(h.replies()).toHaveLength(0);
      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      // Deliberately NOT the Claude echo (`allow: input.allow`): nothing was
      // granted here, so a card reading "Allowed" would be a lie about a
      // request that no longer exists.
      expect(payload(resolved[0])).toEqual({
        permissionId: 'codex:s1:n:99',
        allow: false,
        autoReason: 'aborted',
      });
    });

    it('still reports a genuinely malformed command as invalid_payload', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({ sessionId: 's1', allow: true, requestId: 'req-bad' });
      h.runtime.respondPermission({
        sessionId: 'nope',
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: true,
      });

      expect(h.eventsOf('host.error').map((event) => payload(event).code)).toEqual([
        'invalid_payload',
        'invalid_payload',
      ]);
      expect(h.eventsOf('permission.resolved')).toHaveLength(0);
      expect(h.replies()).toHaveLength(0);
    });
  });

  describe('A11 — every way a request leaves the table without an answer', () => {
    it('stop -> aborted', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.stop({ sessionId: 's1' });

      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      expect(payload(resolved[0])).toEqual({
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        autoReason: 'aborted',
      });
      // The projection lands BEFORE the terminal on this path; the turn/completed
      // path (A12) is the other order. Neither may be depended on.
      const types = typesOf(h.events);
      expect(types.indexOf('permission.resolved')).toBeLessThan(types.indexOf('session.stopped'));
    });

    it('close -> session_closed', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.close({ sessionId: 's1' });

      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      expect(payload(resolved[0]).autoReason).toBe('session_closed');
    });

    it('process exit -> aborted', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.exit({ code: 1, signal: null });

      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      expect(payload(resolved[0]).autoReason).toBe('aborted');
    });

    it('A16 — the server resolving its own request -> aborted, and never a claim that someone decided', async () => {
      // The fileChange capture very likely walks exactly this path: the request
      // and its `serverRequest/resolved` arrive in the same millisecond and the
      // item goes straight to `status: "declined"`. For file_change this is a
      // NORMAL path, not a corner.
      const h = await stoppableTurn();
      h.events.length = 0;
      h.push({
        method: 'serverRequest/resolved',
        params: { threadId: FIXTURE_THREAD, requestId: APPROVAL_ID },
      });

      // No frame: the server has stopped waiting, so a reply would answer
      // nobody. `forgotten` is not a protocol word, and 'aborted' is the closest
      // existing one — but the key must be PRESENT, because omitting it asserts
      // that a human decided (spec §2.4 / L4).
      expect(h.replies()).toHaveLength(0);
      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      expect(payload(resolved[0])).toEqual({
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        autoReason: 'aborted',
      });
      expect(payload(resolved[0])).not.toHaveProperty('decision');
    });

    it('an answered request is not projected a second time', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        decision: 'deny',
      });
      // Every request we answer is followed by one of these.
      h.push({
        method: 'serverRequest/resolved',
        params: { threadId: FIXTURE_THREAD, requestId: APPROVAL_ID },
      });
      h.runtime.close({ sessionId: 's1' });

      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      // A second projection would arrive WITH an autoReason and repaint a card
      // the user answered as "denied automatically".
      expect(payload(resolved[0])).not.toHaveProperty('autoReason');
      expect(h.replies()).toHaveLength(1);
    });
  });

  describe('A12 — a turn that ends with an approval still parked', () => {
    it('answers the request, resolves the card and empties the table', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.push({
        method: 'turn/completed',
        params: {
          threadId: FIXTURE_THREAD,
          turn: { id: FIXTURE_TURN, items: [], status: 'completed' },
        },
      });

      // Without this drain the renderer clears its permission QUEUE on the
      // terminal while `block.resolved` stays false: the card spins until the
      // session is closed.
      const resolved = h.eventsOf('permission.resolved');
      expect(resolved).toHaveLength(1);
      expect(payload(resolved[0])).toEqual({
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        autoReason: 'aborted',
      });
      expect(h.replies()).toHaveLength(1);
      expect(h.replies()[0]).toMatchObject({ id: APPROVAL_ID, result: { decision: 'cancel' } });
      expect(terminalsOf(h.events)).toEqual(['session.completed']);
      // On THIS path the terminal is emitted first (the normalizer writes it
      // from the frame's own status, before the runtime retires the turn), the
      // opposite of the stop path — which is why the store must converge under
      // either order.
      const types = typesOf(h.events);
      expect(types.indexOf('session.completed')).toBeLessThan(types.indexOf('permission.resolved'));

      // Table empty: a later close writes no second frame for the same id.
      h.runtime.close({ sessionId: 's1' });
      expect(h.replies().filter((frame) => frame.id === APPROVAL_ID)).toHaveLength(1);
      expect(h.eventsOf('permission.resolved')).toHaveLength(1);
    });
  });

  describe('A13 — "Deny and stop" ends the turn locally too', () => {
    it('sends cancel, drains the rest, retires the turn and frees the session', async () => {
      const h = await stoppableTurn();
      // A second approval on the same turn: the contract declares one itemId can
      // own several approval callbacks, so a multi-parked turn is a real shape.
      h.push(commandApproval(1));
      h.events.length = 0;
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        decision: 'cancel',
        requestId: 'req-cancel',
      });

      // The user's own decision, on the wire, exactly once...
      expect(h.replies().map((frame) => frame.id)).toEqual([APPROVAL_ID, 1]);
      expect(h.replies()[0].result).toEqual({ decision: 'cancel' });
      // ...and the sibling nobody can answer any more, refused fail-safe.
      expect(h.replies()[1].result).toEqual({ decision: 'cancel' });
      const resolved = h.eventsOf('permission.resolved');
      expect(payload(resolved[0])).toEqual({
        permissionId: permissionIdOf(APPROVAL_ID),
        allow: false,
        decision: 'cancel',
      });
      expect(payload(resolved[1])).toEqual({
        permissionId: permissionIdOf(1),
        allow: false,
        autoReason: 'aborted',
      });
      // Cancel means "the turn is interrupted" on the server side; a second
      // interrupt frame would be shouting at a turn that is already dying.
      expect(h.requestsFor('turn/interrupt')).toHaveLength(0);
      expect(terminalsOf(h.events)).toEqual(['session.stopped']);
      // The status echo is the registry's own reading, not an invented one.
      expect(h.eventsOf('session.status')).toHaveLength(1);
      expect(payload(h.event('session.status')).status).toBe(h.registry.get('s1')?.status);
    });

    it('leaves the session able to send again, instead of busy forever', async () => {
      const h = await stoppableTurn();
      h.runtime.respondPermission({
        sessionId: 's1',
        permissionId: permissionIdOf(APPROVAL_ID),
        decision: 'cancel',
        allow: false,
      });
      h.events.length = 0;
      await h.runtime.send({ sessionId: 's1', text: 'again', requestId: 'req-2' });

      // Falsifies "cancel and hope": if `turn/completed` never arrives for an
      // interrupted turn, a session that did not retire its own turn answers
      // every later send with `session_busy` for the rest of its life.
      expect(h.eventsOf('host.error')).toHaveLength(0);
      expect(h.requestsFor('turn/start')).toHaveLength(2);
    });
  });

  describe('A14 — the bridge writes no session.status of its own', () => {
    it('emits exactly one session.status per status frame fed in', async () => {
      const h = await turnSession();
      await h.runtime.send({ sessionId: 's1', text: PROMPT });
      const routed = replayRecordedTurn(h);
      const statusFrames = routed.filter((method) => method === 'thread/status/changed').length;

      // Conservation, not "none": the recording carries its own status frames,
      // so "the approval path emitted none" can only be stated as a count.
      expect(statusFrames).toBeGreaterThan(0);
      expect(h.eventsOf('session.status')).toHaveLength(statusFrames);
      // Not vacuous — the approval really did travel this replay.
      expect(h.eventsOf('permission.requested')).toHaveLength(1);
      expect(h.eventsOf('permission.resolved')).toHaveLength(1);
    });
  });

  describe('A17 / A18 — the two requests that never become cards', () => {
    it('A17 — an approval with no turn running is refused on the spot', async () => {
      const h = await startedSession();
      h.events.length = 0;
      h.push(commandApproval(0));

      // No normalizer means no diff to correlate, and `stop()` neither tears the
      // session down nor guarantees the interrupt landed — so codex can keep
      // asking after the user pressed Stop. A card here would drag the session
      // back into a busy state it just left.
      expect(h.eventsOf('permission.requested')).toHaveLength(0);
      expect(h.eventsOf('permission.resolved')).toHaveLength(0);
      expect(h.replies()).toHaveLength(1);
      expect(h.replies()[0]).toMatchObject({ id: 0, result: { decision: 'cancel' } });
      // Nothing was registered, so a later close has nothing left to answer.
      h.runtime.close({ sessionId: 's1' });
      expect(h.replies().filter((frame) => frame.id === 0)).toHaveLength(1);
    });

    it('A18 — permissions and elicitation are refused fail-safe, not parked', async () => {
      const h = await stoppableTurn();
      h.events.length = 0;
      h.push({ id: 1, method: 'item/permissions/requestApproval', params: {} });
      h.push({ id: 2, method: 'mcpServer/elicitation/request', params: {} });

      // Parking them is what slice 2c did, and it costs a hung turn: codex sits
      // on `waitingOnApproval` with no card on screen until Stop.
      expect(h.replies()).toHaveLength(2);
      expect(h.replies()[0]).toMatchObject({ id: 1, result: { permissions: {}, scope: 'turn' } });
      expect(h.replies()[1]).toMatchObject({ id: 2, result: { action: 'decline' } });
      expect(h.eventsOf('permission.requested')).toHaveLength(0);
      expect(h.eventsOf('permission.resolved')).toHaveLength(0);

      // The table is untouched: the fileChange approval parked before them is
      // still the only entry, and it is the only thing close() answers.
      h.runtime.close({ sessionId: 's1' });
      expect(h.replies()).toHaveLength(3);
      expect(h.replies()[2]).toMatchObject({ id: APPROVAL_ID, result: { decision: 'cancel' } });
    });
  });
});

/**
 * S3 slice 6 (#8) — the idle sweeper and the send that brings a swept session
 * back.
 *
 * What is being defended here is not memory: it is the session. Reclaiming one
 * app-server is worth nothing if the conversation it was running cannot be
 * continued, so every case below is really one of two questions — "did we take
 * something we were allowed to take" and "can the user still talk to it".
 *
 * The clock and both timers are injected (`makeHarness`), so a 180s threshold is
 * exercised in microseconds and a sweep happens exactly when a test says it
 * does. Real time never moves.
 */
const IDLE_MS = 180 * 1000;

describe('resolveCodexIdleTimeoutMs — the threshold env (G7)', () => {
  const read = (value?: string): number | null =>
    resolveCodexIdleTimeoutMs(value === undefined ? {} : { [CODEX_IDLE_TIMEOUT_ENV]: value });

  it('reads the six documented shapes', () => {
    // Unset is the default; `0` and any negative disable it (codeg's own
    // convention, whose `u64` parse simply rejects the negatives); an
    // unparseable value falls back rather than disabling a memory guard by
    // typo; fractions and exponents are ordinary numbers of seconds.
    expect(read()).toBe(IDLE_MS);
    expect(read('0')).toBeNull();
    expect(read('-1')).toBeNull();
    expect(read('abc')).toBe(IDLE_MS);
    expect(read('1.5')).toBe(1500);
    expect(read('1e9')).toBe(1e12);
  });

  it('treats an empty value as unset, not as zero', () => {
    // `Number('') === 0`, so an env var that exists and says nothing would
    // otherwise turn the sweeper OFF — the opposite of "not configured", and
    // silently. This is why the empty check runs before the parse.
    expect(read('')).toBe(IDLE_MS);
  });
});

describe('isCodexIdleSweepable — six conditions, six vetoes (G6)', () => {
  /** A session that satisfies every condition, so each case can break ONE. */
  const SWEEPABLE: CodexIdleView = {
    threadId: FIXTURE_THREAD,
    rolloutBacked: true,
    hasTurn: false,
    pendingCount: 0,
    torndown: false,
    reviving: false,
    lastActivityAt: 0,
  };
  const judge = (over: Partial<CodexIdleView>): boolean =>
    isCodexIdleSweepable({ ...SWEEPABLE, ...over }, IDLE_MS, IDLE_MS);

  it('sweeps a session that satisfies all of them', () => {
    // The positive control. Without it every veto below could pass vacuously.
    expect(judge({})).toBe(true);
  });

  it('refuses a session with no thread id — the handshake is still in flight', () => {
    // Killing this one aborts a create or a resume the user is waiting on.
    expect(judge({ threadId: undefined })).toBe(false);
  });

  it('refuses a session with no rollout file behind it', () => {
    // A zero-turn thread cannot be resumed at all [实测 -32600 no rollout], so
    // reclaiming it would DELETE the session rather than park it (L8).
    expect(judge({ rolloutBacked: false })).toBe(false);
  });

  it('refuses a session with a turn in flight', () => {
    // The link can be quiet for minutes while the model thinks.
    expect(judge({ hasTurn: true })).toBe(false);
  });

  it('refuses a session holding a card the user can still answer', () => {
    expect(judge({ pendingCount: 1 })).toBe(false);
  });

  it('refuses a session that is already leaving or already coming back', () => {
    expect(judge({ torndown: true })).toBe(false);
    expect(judge({ reviving: true })).toBe(false);
  });

  it('refuses a session that is inside the threshold, to the millisecond', () => {
    expect(isCodexIdleSweepable(SWEEPABLE, IDLE_MS - 1, IDLE_MS)).toBe(false);
    // The boundary is inclusive: "at least this long" is what the env says.
    expect(isCodexIdleSweepable(SWEEPABLE, IDLE_MS, IDLE_MS)).toBe(true);
  });
});

/**
 * The runtime half of G6: the mapping from a live session onto the view above.
 * The pure test cannot see it, and a swapped field there (`hasTurn: turn ===
 * null`) would sweep exactly the sessions that must never be swept.
 */
/**
 * A session with ONE COMPLETED TURN behind it — the minimum shape the sweeper
 * may reclaim, because the completed turn is what puts a rollout file on disk.
 */
async function sweepableSession(options: HarnessOptions = {}): Promise<Harness> {
  const h = await turnSession(options);
  await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-send' });
  replayRecordedTurn(h);
  await h.waitFor(() => terminalsOf(h.events).length === 1, 'the turn to end');
  h.events.length = 0;
  return h;
}

function killsOf(slice: ConnectionSlice): string[] {
  return slice.ops.filter((op) => op.startsWith('kill:'));
}

/**
 * A question request shaped the way the recorded one is: `question` is the
 * field that decides whether a card can be rendered at all, so a request
 * without it is REFUSED at the door and never reaches the pending table.
 */
function questionRequest(id: number): Record<string, unknown> {
  return {
    id,
    method: 'item/tool/requestUserInput',
    params: {
      threadId: FIXTURE_THREAD,
      questions: [{ id: 'q1', header: 'Host', question: 'Which host?', options: [{ label: 'A' }] }],
    },
  };
}

describe('codexRuntime — the idle sweeper takes only what it may (G6/G8/G15)', () => {
  it('starts exactly one interval, at codeg s cadence, and unrefs it', async () => {
    const h = await sweepableSession();

    expect(h.sweeper()?.ms).toBe(CODEX_SWEEP_INTERVAL_MS);
    // An interval that exists to FREE resources must never be the reason the
    // Host process cannot exit when Main closes it.
    expect(h.sweeper()?.unrefs).toBe(1);
    // Idempotent: a second session must not start a second sweeper.
    h.runtime.createSession({ sessionId: 's2', workspacePath: '/work/repo' });
    await h.waitFor(() => h.connections.length === 2, 'the second session');
    expect(h.deadlines).toEqual([]);
  });

  it('reclaims an idle session silently, keeping the binding that can reopen it', async () => {
    const h = await sweepableSession();
    h.advance(IDLE_MS);
    h.sweepTick();

    // The process is gone...
    expect(killsOf(h.connections[0])).toEqual(['kill:idle sweep']);
    // ...the row says so — and this line is NOT redundant with the exit path:
    // `teardown` sets `torndown` first and `onExit` returns on a torn-down
    // state, so the `disconnected` a crash writes never runs for a kill we
    // asked for.
    expect(h.registry.get('s1')?.status).toBe('disconnected');
    // ...but the binding survives, because it is the resume handle. Deleting it
    // would make the next send `session_not_found`, which the renderer answers
    // by building a brand-new thread over this one.
    expect(h.registry.get('s1')?.runtimeIdentity).toBe(FIXTURE_THREAD);
    expect(h.registry.get('s1')?.agent).toBe(CODEX_AGENT);
    // And the user was told NOTHING: they never asked for this, and a
    // `session.failed` here would report a crash that did not happen.
    expect(h.events).toEqual([]);
    // The state itself is gone rather than merely flagged — `stop` needs one,
    // and now says so.
    h.runtime.stop({ sessionId: 's1', requestId: 'req-stop' });
    expect(payload(h.event('host.error')).code).toBe('session_not_found');
  });

  it('does not reclaim a session whose turn is still running', async () => {
    // A SECOND turn on a session that already has a completed one, so every
    // other condition says "reclaimable" and the live turn is the only thing
    // standing between it and a kill that abandons the model mid-answer. (A
    // fresh session would be held back by its missing rollout file instead,
    // which would leave this rule untested.)
    const h = await sweepableSession();
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-2' });
    // The link has been silent since: a model that thinks for four minutes is
    // not an idle session.
    h.advance(IDLE_MS * 10);
    h.sweepTick();

    expect(killsOf(h.connections[0])).toEqual([]);
    expect(h.registry.get('s1')?.status).not.toBe('disconnected');
  });

  it('does not reclaim a session that has never completed a turn', async () => {
    // The zero-turn case (L8): no rollout file exists, so `thread/resume` would
    // answer `-32600 no rollout found` and the session would be gone for good.
    const h = await startedSession();
    h.advance(IDLE_MS * 10);
    h.sweepTick();

    expect(killsOf(h.connections[0])).toEqual([]);
  });

  it('does not reclaim a session still holding a question card', async () => {
    const h = await sweepableSession();
    // A question parked mid-turn SURVIVES the turn's end (only approvals are
    // drained there), so this is a real state: no turn, but a card on screen
    // that the user can still answer.
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-2' });
    h.push(questionRequest(7));
    replayRecordedTurn(h, { turnId: 'turn-2' });
    await h.waitFor(() => h.eventsOf('question.requested').length === 1, 'the card');
    h.advance(IDLE_MS);
    h.sweepTick();

    expect(killsOf(h.connections[0])).toEqual([]);

    // Answered — now nothing is waiting on the user and the session is idle.
    h.runtime.respondQuestion({
      sessionId: 's1',
      questionId: 'codex:s1:n:7',
      answers: { q1: 'a' },
    });
    h.advance(IDLE_MS);
    h.sweepTick();
    expect(killsOf(h.connections[0])).toEqual(['kill:idle sweep']);
  });

  it('does not reclaim before the threshold, and does on the first tick after it', async () => {
    const h = await sweepableSession();
    h.advance(IDLE_MS - 1);
    h.sweepTick();
    expect(killsOf(h.connections[0])).toEqual([]);

    h.advance(1);
    h.sweepTick();
    expect(killsOf(h.connections[0])).toEqual(['kill:idle sweep']);
  });

  it('counts a frame in EITHER direction as activity (O20)', async () => {
    const h = await sweepableSession();

    // Inbound, and deliberately a frame the runtime drops on the floor: a
    // status notification outside a turn changes no session state at all, but
    // it is still codex talking to us about this session.
    h.advance(IDLE_MS - 1);
    h.push({
      method: 'thread/status/changed',
      params: { threadId: FIXTURE_THREAD, status: { type: 'idle' } },
    });
    h.advance(IDLE_MS - 1);
    h.sweepTick();
    expect(killsOf(h.connections[0])).toEqual([]);

    // Outbound, from the path a runtime-level timestamp could never see: the
    // pending table's reply closure writes straight into the connection.
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-2' });
    h.push(questionRequest(8));
    replayRecordedTurn(h, { turnId: 'turn-2' });
    h.advance(IDLE_MS - 1);
    h.runtime.respondQuestion({
      sessionId: 's1',
      questionId: 'codex:s1:n:8',
      answers: { q1: 'a' },
    });
    expect(h.connections[0].ops).toContain('reply:8');
    h.advance(IDLE_MS - 1);
    h.sweepTick();
    expect(killsOf(h.connections[0])).toEqual([]);
  });

  it('starts a sweeper for a process that only ever RESUMED a session (O14)', async () => {
    // The restart shape: the app comes back, the user opens an old session from
    // the history list and never creates a new one. Hanging the sweeper off
    // `createSession` alone would leave this process holding an app-server per
    // reopened session with nothing watching them.
    const h = makeHarness();
    h.runtime.resumeSession({
      sessionId: 's-resume',
      workspacePath: '/work/repo',
      runtimeIdentity: RECORDED_THREAD,
      requestId: 'req-resume',
    });
    await h.waitForEvent('session.history');
    h.events.length = 0;

    expect(h.sweeper()?.ms).toBe(CODEX_SWEEP_INTERVAL_MS);
    h.advance(IDLE_MS);
    h.sweepTick();

    // An answered `thread/resume` IS the proof the rollout file exists, so a
    // cold-resumed session is sweepable straight away.
    expect(killsOf(h.connections[0])).toEqual(['kill:idle sweep']);
    expect(h.events).toEqual([]);
  });

  it('stops the interval when the last session goes, and never starts one when disabled', async () => {
    const h = await sweepableSession();
    h.advance(IDLE_MS);
    h.sweepTick();
    // Nothing left to watch. The pairing that makes this safe is on the other
    // side: every insertion point re-ensures the sweeper, so a revived session
    // is watched again.
    expect(h.sweeper()?.stops).toBe(1);

    const off = await turnSession({ env: { [CODEX_IDLE_TIMEOUT_ENV]: '0' } });
    expect(off.sweeper()).toBeUndefined();
    off.advance(IDLE_MS * 100);
    expect(() => off.sweepTick()).toThrow(/no idle sweeper/);
    expect(off.connections[0].ops.filter((op) => op.startsWith('kill:'))).toEqual([]);
  });
});

/**
 * The other half of #8: a swept session is only reclaimed if the user can pick
 * the conversation up again. These cases are the pickup.
 *
 * Everything here is QUIET on purpose. The renderer was never told the session
 * went away, so it must not be told it came back either — a `session.resumed` +
 * `session.history` pair would replay a transcript the user is already looking
 * at and reset the chat they are typing into.
 */
describe('codexRuntime — send() revives a swept session (G9/G13)', () => {
  /**
   * What `thread/resume` answers on the revive path. Only the POSTURE is read
   * there (no transcript is replayed), so this carries the echo dialect over the
   * thread the swept session actually owns, rather than pointing the whole
   * recorded result at the wrong thread.
   */
  const REVIVED_RESULT: Record<string, unknown> = {
    thread: { id: FIXTURE_THREAD, turns: [] },
    approvalPolicy: 'on-request',
    sandbox: { type: 'workspaceWrite' },
  };

  async function sweptSession(options: HarnessOptions = {}): Promise<Harness> {
    const h = await sweepableSession({ threadResumeResult: REVIVED_RESULT, ...options });
    h.advance(IDLE_MS);
    h.sweepTick();
    h.events.length = 0;
    return h;
  }

  it('reopens the thread over ONE new link and runs the turn on it', async () => {
    const h = await sweptSession();
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-again' });

    expect(h.connections).toHaveLength(2);
    // `thread/resume`, never `thread/start`: a new thread would leave the user's
    // conversation on disk and hand them an empty one under the same row.
    expect(h.connections[1].ops).toEqual([
      'write:initialize',
      'write:initialized',
      'write:thread/resume',
      'write:turn/start',
    ]);
    expect(h.connections[1].requestsFor('thread/resume')[0].params).toEqual({
      threadId: FIXTURE_THREAD,
    });
    expect(h.connections[1].requestsFor('turn/start')[0].params).toEqual(
      buildTurnStartParams({ threadId: FIXTURE_THREAD, text: PROMPT })
    );
    // H9 stays double-layered on this path too: the isolated home is re-seeded
    // with the same posture object (layer 1), and the echo is verified below in
    // its own case (layer 2).
    expect(h.ensureHomeInputs).toHaveLength(2);
    expect(h.ensureHomeInputs[1].permission).toBe(CODEX_PERMISSION_DEFAULT);
    // Quiet. Nothing that would repaint the conversation, and no error either.
    expect(h.eventsOf('session.resumed')).toEqual([]);
    expect(h.eventsOf('session.history')).toEqual([]);
    expect(h.eventsOf('host.error')).toEqual([]);
  });

  it('leaves the status projector open afterwards (O3)', async () => {
    const h = await sweptSession();
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-again' });
    h.events.length = 0;

    // `statusGated` is released by the resume CONTRACT, which this path never
    // emits — so the revive has to release it itself. Left set, the session
    // could send but could never look busy again, for the rest of its life.
    h.push({
      method: 'thread/status/changed',
      params: { threadId: FIXTURE_THREAD, status: { type: 'active', activeFlags: [] } },
    });

    expect(h.eventsOf('session.status').map((event) => payload(event).status)).toEqual(['running']);
    // The registry converges through the same frame: the sweep left it
    // `disconnected`, and this is what takes it off that reading.
    expect(h.registry.get('s1')?.status).toBe('running');
  });

  it('watches the revived session again and can reclaim it a second time', async () => {
    const h = await sweptSession();
    // The sweep that produced it emptied the map and stopped the interval.
    expect(h.intervals).toHaveLength(1);
    expect(h.intervals[0].stops).toBe(1);

    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-again' });
    replayRecordedTurn(h, { turnId: 'turn-revived' });
    await h.waitFor(() => terminalsOf(h.events).length === 1, 'the revived turn to end');

    // Without re-ensuring, a revived session would be held until the app quits.
    expect(h.intervals).toHaveLength(2);
    expect(h.intervals[1].unrefs).toBe(1);
    h.advance(IDLE_MS);
    h.sweepTick();
    expect(killsOf(h.connections[1])).toEqual(['kill:idle sweep']);
  });

  it('refuses a second send while the revive is in flight, retryably (F16)', async () => {
    const h = await sweptSession();
    // The option object is read per frame, so flipping it now stalls the
    // REVIVE's handshake without having stalled the create that produced the
    // session.
    h.options.answerInitialize = false;
    const sending = h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    await h.waitFor(() => h.connections.length === 2, 'the revive link');

    await h.runtime.send({ sessionId: 's1', text: 'again', requestId: 'req-2' });

    // The placeholder state has no thread id yet, which is the gate `send`
    // already had — no invented turn is needed to hold the door.
    const error = h.event('host.error');
    expect(payload(error).code).toBe('session_busy');
    expect(error?.requestId).toBe('req-2');
    expect(h.connections).toHaveLength(2);
    expect(h.connections[1].requestsFor('turn/start')).toEqual([]);

    h.deadlines[0].fire();
    await sending;
  });

  it('does not let a sweep tick kill the link that is reopening the thread', async () => {
    const h = await sweptSession();
    h.options.answerInitialize = false;
    const sending = h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    await h.waitFor(() => h.connections.length === 2, 'the revive link');

    // The placeholder's clock starts at construction, so a tick landing inside
    // a slow revive would otherwise reclaim the very link that is bringing the
    // session back — and the send would fail for a reason we caused.
    h.advance(IDLE_MS * 10);
    h.sweepTick();
    expect(killsOf(h.connections[1])).toEqual([]);

    h.deadlines[0].fire();
    await sending;
  });

  it('refuses a sidebar resume while the revive is in flight (O13)', async () => {
    const h = await sweptSession();
    h.options.answerInitialize = false;
    const sending = h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    await h.waitFor(() => h.connections.length === 2, 'the revive link');
    h.events.length = 0;

    h.runtime.resumeSession({
      sessionId: 's1',
      workspacePath: '/work/repo',
      runtimeIdentity: FIXTURE_THREAD,
      requestId: 'req-resume',
    });

    // Guard ③ would otherwise take this: `connection.alive` is true from the
    // moment the link is constructed, so the sidebar's resume would be answered
    // with `thread/turns/list` over a link that has not finished `initialize`.
    const error = h.event('host.error');
    expect(payload(error).code).toBe('session_busy');
    expect(error?.requestId).toBe('req-resume');
    expect(h.connections[1].requestsFor('thread/turns/list')).toEqual([]);
    expect(h.eventsOf('session.resumed')).toEqual([]);

    h.deadlines[0].fire();
    await sending;
  });
});

describe('codexRuntime — a revive that cannot happen says so (G10/G11/G14)', () => {
  const REVIVED_RESULT: Record<string, unknown> = {
    thread: { id: FIXTURE_THREAD, turns: [] },
    approvalPolicy: 'on-request',
    sandbox: { type: 'workspaceWrite' },
  };

  async function sweptSession(options: HarnessOptions = {}): Promise<Harness> {
    const h = await sweepableSession({ threadResumeResult: REVIVED_RESULT, ...options });
    h.advance(IDLE_MS);
    h.sweepTick();
    h.events.length = 0;
    return h;
  }

  it('refuses a thread whose posture does not check out (H9 layer 2)', async () => {
    const h = await sweptSession();
    // The REAL recorded result: that capture ran under the developer's own
    // `~/.codex`, whose `danger-full-access` is what came back. A revive that
    // accepted it would run the session with every approval prompt switched off.
    h.options.threadResumeResult = RECORDED_RESUME_RESULT;
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-again' });

    const error = h.event('host.error');
    expect(payload(error).code).toBe(CODEX_REVIVE_FAILED_CODE);
    expect(String(payload(error).message)).toContain('permission posture');
    // Nothing was sent on a session we could not vouch for, and the process it
    // opened is gone rather than left running with a posture we refused.
    expect(h.connections[1].requestsFor('turn/start')).toEqual([]);
    expect(killsOf(h.connections[1])).toHaveLength(1);
    expect(h.eventsOf('session.failed')).toEqual([]);
  });

  it('drops a thread whose rollout is gone and converges back to session_not_found', async () => {
    const h = await sweptSession();
    h.options.threadResumeError = {
      code: -32600,
      message: `no rollout found for thread id ${FIXTURE_THREAD}`,
    };
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    expect(payload(h.event('host.error')).code).toBe(CODEX_REVIVE_FAILED_CODE);
    h.events.length = 0;

    // Off the list: no retry can succeed against a rollout that is not there, so
    // the session converges back to the semantics it had before this path
    // existed — the renderer's own new-thread recovery included.
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-2' });
    expect(payload(h.event('host.error')).code).toBe('session_not_found');
    expect(h.connections).toHaveLength(2);
  });

  it('keeps a session whose revive failed for an infrastructure reason', async () => {
    const h = await sweptSession();
    h.options.initializeError = { code: -32603, message: 'handshake exploded' };
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    expect(payload(h.event('host.error')).code).toBe(CODEX_REVIVE_FAILED_CODE);
    expect(h.connections).toHaveLength(2);
    h.events.length = 0;

    // Still on the list — a handshake that failed once is not a thread that is
    // gone — and the retry really does reopen it.
    h.options.initializeError = undefined;
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-2' });
    expect(h.connections).toHaveLength(3);
    expect(h.connections[2].requestsFor('thread/resume')[0].params).toEqual({
      threadId: FIXTURE_THREAD,
    });
    expect(h.eventsOf('host.error')).toEqual([]);
  });

  it('reports a revive that could not start codex at all, and keeps the session', async () => {
    let broken = false;
    const h = await sweptSession({
      resolveLaunch: () =>
        broken
          ? {
              ok: false,
              code: 'codex_entry_unresolved',
              message: 'Codex entry not found: no @openai/codex bin next to node.',
              inspected: [],
            }
          : { ok: true, plan: PLAN },
    });
    broken = true;
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });

    expect(payload(h.event('host.error')).code).toBe(CODEX_REVIVE_FAILED_CODE);
    // Nothing was spawned, so there was nothing to tear down.
    expect(h.connections).toHaveLength(1);
    h.events.length = 0;

    broken = false;
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-2' });
    expect(h.connections).toHaveLength(2);
    expect(h.eventsOf('host.error')).toEqual([]);
  });

  it('gives up on its OWN deadline, not the transport s (O10)', async () => {
    const h = await sweptSession();
    h.options.answerInitialize = false;
    const sending = h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    await h.waitFor(() => h.deadlines.length === 1, 'the revive deadline');

    // The component deadlines add up to 75s (15s initialize + a 60s request),
    // while the renderer abandons a send at 45s — so without a chain-level
    // budget the user's send fails generically and the Host keeps working.
    expect(h.deadlines[0].ms).toBe(CODEX_REVIVE_DEADLINE_MS);
    expect(h.deadlines[0].unrefs).toBe(1);
    h.deadlines[0].fire();
    await sending;

    const error = h.event('host.error');
    expect(payload(error).code).toBe(CODEX_REVIVE_FAILED_CODE);
    expect(String(payload(error).message)).toContain('timed out');
    expect(killsOf(h.connections[1])).toHaveLength(1);
    // Cancelled once it has lost, or every send leaves a timer behind.
    expect(h.deadlines[0].stops).toBe(1);
  });

  it('never answers a failed revive with the code that makes the renderer swap the thread', async () => {
    // `session_not_found` on a direct send is the renderer's signal to close
    // this session, create a fresh one and OVERWRITE the persisted
    // runtimeIdentity. Reusing it for a failed revive would turn "we could not
    // reopen your thread" into a silent session swap — the loudest possible
    // data loss dressed up as a fail-safe.
    for (const failure of [
      { threadResumeError: { code: -32600, message: 'no rollout found for thread id x' } },
      { initializeError: { code: -32603, message: 'handshake exploded' } },
      { threadResumeResult: RECORDED_RESUME_RESULT },
    ]) {
      const h = await sweptSession();
      Object.assign(h.options, failure);
      await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });

      const error = h.event('host.error');
      expect(payload(error).code).toBe(CODEX_REVIVE_FAILED_CODE);
      expect(payload(error).code).not.toBe('session_not_found');
      // Non-fatal and correlated both ways, like every other refusal: the
      // Composer has to be able to fail THIS message instead of spinning.
      expect(payload(error).fatal).toBe(false);
      expect(error?.sessionId).toBe('s1');
      expect(error?.requestId).toBe('req-1');
    }
  });

  it('refuses to revive a row whose binding no longer fits (defensive)', async () => {
    // Neither state below is reachable through this runtime today: only a codex
    // session can be swept, and a swept one always has its thread id. Both
    // checks are here because the cost of being wrong is asymmetric — spawning
    // a codex for a row whose sends go to the Claude runtime, or resuming
    // `undefined` as a thread — so they are pinned rather than trusted.
    const foreign = await sweptSession();
    foreign.registry.delete('s1');
    // Rebound to the other runtime, thread handle and all: the agent is the
    // ONLY thing left that can refuse this one.
    foreign.registry.resume({
      sessionId: 's1',
      workspacePath: '/work/repo',
      runtimeIdentity: FIXTURE_THREAD,
      agent: CLAUDE_CODE_AGENT,
    });
    await foreign.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    expect(payload(foreign.event('host.error')).code).toBe('session_not_found');
    expect(foreign.connections).toHaveLength(1);

    const unbound = await sweptSession();
    unbound.registry.delete('s1');
    unbound.registry.create({ sessionId: 's1', workspacePath: '/work/repo', agent: CODEX_AGENT });
    await unbound.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    expect(payload(unbound.event('host.error')).code).toBe('session_not_found');
    expect(unbound.connections).toHaveLength(1);
  });

  it('leaves a CRASHED session on the ordinary session_not_found path (O12)', async () => {
    const h = await sweepableSession();
    h.exit({ code: 1, signal: null });
    await h.waitForEvent('session.failed');
    h.events.length = 0;

    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });

    // The judgement is the sweep LIST, not "the state is missing". This user was
    // already told the session died; reopening it silently would replace a
    // failure they saw with a recovery they cannot audit.
    expect(payload(h.event('host.error')).code).toBe('session_not_found');
    expect(h.connections).toHaveLength(1);
  });

  it('leaves a failed cold resume on the ordinary session_not_found path (O12)', async () => {
    const h = makeHarness({ threadResumeError: { code: -32603, message: 'resume exploded' } });
    h.runtime.resumeSession({
      sessionId: 's-resume',
      workspacePath: '/work/repo',
      runtimeIdentity: RECORDED_THREAD,
      requestId: 'req-resume',
    });
    await h.waitForEvent('session.history');
    h.events.length = 0;

    await h.runtime.send({ sessionId: 's-resume', text: PROMPT, requestId: 'req-1' });

    expect(payload(h.event('host.error')).code).toBe('session_not_found');
    expect(h.connections).toHaveLength(1);
  });

  it('takes a swept session off the revive list once the user reopens it themselves', async () => {
    const h = await sweptSession();
    h.options.threadResumeError = { code: -32603, message: 'resume exploded' };
    h.runtime.resumeSession({
      sessionId: 's1',
      workspacePath: '/work/repo',
      runtimeIdentity: FIXTURE_THREAD,
      requestId: 'req-resume',
    });
    await h.waitForEvent('session.history');
    h.events.length = 0;

    // The reclaim was quiet; this resume was not. Its failure has already been
    // reported through the degradation contract, so the next send must not go
    // spawning another codex behind a banner the user is already reading — it
    // is an ordinary failed resume from here on.
    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });
    expect(payload(h.event('host.error')).code).toBe('session_not_found');
    expect(h.connections).toHaveLength(2);
  });

  it('does not revive a session that was closed after it was swept', async () => {
    const h = await sweptSession();
    h.runtime.close({ sessionId: 's1', requestId: 'req-close' });
    h.events.length = 0;

    await h.runtime.send({ sessionId: 's1', text: PROMPT, requestId: 'req-1' });

    expect(payload(h.event('host.error')).code).toBe('session_not_found');
    expect(h.connections).toHaveLength(1);
  });
});
