    h.events.length = 0;
    h.runtime.stop({ sessionId: 's1' });
    // Everything codex had already queued behind the approval, `turn/completed`
    // included. The registered cost is that these are lost; the failure would be
    // a second terminal for a turn the renderer has already retired.
    replayRecordedTurn(h, { from: 10 });

    expect(terminalsOf(h.events)).toEqual(['session.stopped']);
    expect(h.logs.some((line) => line.includes('outside a turn'))).toBe(true);
    // Codex's own status frames still land, which is what converges the session
